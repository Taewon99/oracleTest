-- RECEIVING 테이블에 상품이 입력되면 PRODUCT 수량을 상품 테이블의 재고 수량에 추가하는 트리거 작성
CREATE OR REPLACE TRIGGER TRG_IN
    AFTER INSERT
    ON RECEIVING
    FOR EACH ROW
    BEGIN
        UPDATE PRODUCT
            SET STOCK = STOCK + :NEW.RQTY
            WHERE PCODE = :NEW.PCODE;
    END;
/

