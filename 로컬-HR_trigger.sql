-- 사원 테이블에 새로운 데이터 즉 신입 사원이 들어오면 급여 테이블에 새로운 데이터를 자동으로 생성하고 싶을 경우, 사원 테이블에 트리거를 설정하여 구연할 수 있다.
CREATE TABLE SAL01(
    SALNO NUMBER(4),
    SAL NUMBER,
    EMPNO NUMBER(4)
    );

ALTER TABLE SAL01 ADD CONSTRAINTS SAL01_SALNO_PK PRIMARY KEY(SALNO);
ALTER TABLE SAL01 ADD CONSTRAINTS SAL01_EMPNO_FK FOREIGN KEY(EMPNO) REFERENCES EMP01(EMPNO);

CREATE SEQUENCE SAL01_SEQ
    START WITH 1
    INCREMENT BY 1
    MINVALUE 1
    MAXVALUE 100000
    NOCYCLE
    CACHE 2;

CREATE OR REPLACE TRIGGER EMP01_TRIGGER2
    AFTER INSERT
    ON EMP01
    FOR EACH ROW
    BEGIN
        INSERT INTO SAL01 VALUES(SAL01_SEQ.NEXTVAL, 100000, :NEW.EMPNO);
        DBMS_OUTPUT.PUT_LINE(:NEW.EMPNO ||'번의 사원이 SAL01에 잘 들어왔습니다');
    END;
/

