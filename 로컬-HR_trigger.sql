-- 갱신 트리거 만들고 입고 수량 변경하기
CREATE OR REPLACE TRIGGER TRG_UP
    AFTER UPDATE
    ON RECEIVING
    FOR EACH ROW
    BEGIN
        UPDATE PRODUCT
        SET STOCK = STOCK + (-:OLD.RQTY +:NEW.RQTY)
        WHERE PCODE = :NEW.PCODE;
    END;
/

UPDATE RECEIVING SET RQTY = 10 WHERE RNO = 4;

SELECT * FROM PRODUCT;
SELECT * FROM RECEIVING;

-- 삭제 트리거 만들고 RECEIVING 테이블에 상품이 삭제되면 PRODUCT에서 삭제 수량을 빼준다
CREATE OR REPLACE TRIGGER TRG_DEL
    AFTER DELETE
    ON RECEIVING
    FOR EACH ROW
    BEGIN
        UPDATE PRODUCT SET STOCK = STOCK -(:OLD.RQTY) WHERE PCODE = :OLD.PCODE;
    END;
/

