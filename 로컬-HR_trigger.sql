-- 입고 테이블에 상품이 입력되면 입고 수량을 상품 테이블의 재고 수량에 추가하는 트리거 작성해 보자.

-- PRODUCT 테이블 작성
CREATE TABLE PRODUCT(
    PCODE CHAR(6),
    PNAME VARCHAR(12) NOT NULL,
    PCOMPANY VARCHAR(12),
    PPRICE NUMBER(8),
    STOCK NUMBER DEFAULT 0,
    CONSTRAINT PRODUCT_PCODE_PK PRIMARY KEY(PCODE)
);

-- RECEIVING 테이블 작성
CREATE TABLE RECEIVING(
    RNO NUMBER(6),
    PCODE CHAR(6),
    PDATE DATE DEFAULT SYSDATE,
    RQTY NUMBER(6),
    RPRICE NUMBER(8),
    RAMOUNT NUMBER(8),
    CONSTRAINT RECEIVING_RNO_PK PRIMARY KEY(RNO),
    CONSTRAINT RECIEVING_PCODE_FK FOREIGN KEY(PCODE) REFERENCES PRODUCT(PCODE)
);

